// Builds dist/cli.js (the npx entry point) and dist/ui (the pre-built browser app).

import { build } from "esbuild";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const pkg = JSON.parse(await readFile("package.json", "utf8"));

// Ship the full notices from the exact versions whose code/fonts we bundle.
const bundledPackages = [
  "preact",
  "@phosphor-icons/react",
  "marked",
  "@fontsource/geist-sans",
  "@fontsource/geist-mono",
];
const notices = await Promise.all(
  bundledPackages.map(async (name) => {
    const dependency = JSON.parse(await readFile(`node_modules/${name}/package.json`, "utf8"));
    const license = await readFile(`node_modules/${name}/LICENSE`, "utf8");
    return `## ${name}@${dependency.version}

Source: [${name}](https://www.npmjs.com/package/${name})

License supplied with the package (${dependency.license}):

\`\`\`text
${license.trimEnd()}
\`\`\``;
  }),
);
const brandLicense = await readFile("ui/assets/brands/LICENSE", "utf8");
notices.push(`## Agent brand marks (Lobe Icons)

Source: [Lobe Icons](https://github.com/lobehub/lobe-icons)

The Claude and OpenAI SVG marks are vendored from Lobe Icons. Brand names and marks belong
to their respective owners and identify supported agents; they do not imply endorsement.

License supplied with the artwork (MIT):

\`\`\`text
${brandLicense.trimEnd()}
\`\`\``);
await writeFile(
  "THIRD_PARTY_NOTICES.md",
  "# Third-party notices\n\n" +
    "Runlens's own code is licensed under MIT; see [LICENSE](LICENSE). " +
    "Bundled third-party code and fonts retain the licenses reproduced below.\n\n" +
    "This file is generated by `scripts/build.mjs` from the installed package versions. " +
    "Rebuild after dependency updates to refresh their notices.\n\n" +
    notices.join("\n\n") +
    "\n",
);

// All output names are fixed. Write them in place so rebuilds also work when the
// output directory is mounted or a local viewer already has it open.
await mkdir("dist/ui", { recursive: true });

await build({
  entryPoints: ["src/cli.ts"],
  outfile: "dist/cli.js",
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  banner: { js: "#!/usr/bin/env node" },
  define: { __VERSION__: JSON.stringify(pkg.version) },
  logLevel: "warning",
});

await build({
  entryPoints: ["ui/main.tsx"],
  outfile: "dist/ui/app.js",
  bundle: true,
  platform: "browser",
  target: "es2022",
  format: "esm",
  jsx: "automatic",
  jsxImportSource: "preact",
  loader: { ".svg": "base64" },
  // Phosphor icons are written for React; Preact's compat layer runs them unchanged.
  alias: {
    react: "preact/compat",
    "react-dom": "preact/compat",
    "react/jsx-runtime": "preact/jsx-runtime",
  },
  minify: true,
  logLevel: "warning",
});

await copyFile("ui/index.html", "dist/ui/index.html");
await build({
  entryPoints: ["ui/styles/index.css"],
  outfile: "dist/ui/styles.css",
  bundle: true,
  target: "es2022",
  external: ["/*.woff2"],
  minify: true,
  logLevel: "warning",
});

// Fonts ship with the package instead of loading from a font CDN: nothing leaves the machine.
const fonts = {
  "geist-400.woff2": "@fontsource/geist-sans/files/geist-sans-latin-400-normal.woff2",
  "geist-500.woff2": "@fontsource/geist-sans/files/geist-sans-latin-500-normal.woff2",
  "geist-600.woff2": "@fontsource/geist-sans/files/geist-sans-latin-600-normal.woff2",
  "geist-mono-400.woff2": "@fontsource/geist-mono/files/geist-mono-latin-400-normal.woff2",
  "geist-mono-500.woff2": "@fontsource/geist-mono/files/geist-mono-latin-500-normal.woff2",
};
for (const [name, source] of Object.entries(fonts)) {
  await copyFile(`node_modules/${source}`, `dist/ui/${name}`);
}

console.log(`Built runlens ${pkg.version} → dist/`);
